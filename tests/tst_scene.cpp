    void savesAndLoadsTheSameScene() {
        QTemporaryDir directory;
        const auto path = directory.path() + "/scene.json";
        Scene scene;
        scene.background = "#010203";
        auto box = rectangle("box-1", "Box");
        box.x = 0.1;
        box.y = -2.5;
        box.width = 1234.5678;
        box.color = "#ABCDEF";
        box.controllable = true;
        auto text = label("text-1", "Label", "a \"quoted\" \\ value");
        text.scale = 40;
        scene.items = {box, text};

        QString error = "stale";
        QVERIFY2(saveScene(path, scene, error), qPrintable(error));
        QVERIFY(error.isEmpty());
        const auto loaded = loadScene(path);
        QVERIFY2(loaded.scene.has_value(), qPrintable(loaded.error));
        QCOMPARE(loaded.scene->background, scene.background);
        QCOMPARE(loaded.scene->items.size(), 2);
        for (qsizetype index = 0; index < 2; ++index) {
            const auto& before = scene.items[index];
            const auto& after = loaded.scene->items[index];
            QCOMPARE(after.id, before.id);
            QCOMPARE(after.type, before.type);
            QCOMPARE(after.name, before.name);
            QCOMPARE(after.x, before.x);
            QCOMPARE(after.y, before.y);
            QCOMPARE(after.color, before.color);
            QCOMPARE(after.controllable, before.controllable);
        }
        QCOMPARE(loaded.scene->items[0].width, box.width);
        QCOMPARE(loaded.scene->items[0].height, box.height);
        QCOMPARE(loaded.scene->items[1].scale, 40);
        QCOMPARE(loaded.scene->items[1].text, text.text);
        QCOMPARE(generateSceneHeader(*loaded.scene), generateSceneHeader(scene));
    }

