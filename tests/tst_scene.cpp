// The header from docs/scene-format.md, except for the width of the text item. The doc prints 642.0f,
// but its own rule gives (9 * 6 - 1) * 12 = 636 for "Hello PS5", so this follows the rule.
const QByteArray DocHeader = R"cpp(// Generated by AnyDevKit Studio from scene.json. Do not edit.
#pragma once

#include <array>
#include <cstdint>
#include <string_view>

namespace GeneratedScene {

enum class Kind : std::uint8_t { Rectangle, Text };

struct Item {
    Kind kind;
    float x, y, width, height;
    float red, green, blue;
    float textScale;
    std::string_view text;
    bool controllable;
};

inline constexpr std::array<float, 3> Background{0.082353f, 0.109804f, 0.227451f};
inline constexpr std::array<Item, 2> Items{{
    {Kind::Rectangle, 120.0f, 300.0f, 160.0f, 160.0f, 1.0f, 0.823529f, 0.247059f, 0.0f, "", true},
    {Kind::Text, 400.0f, 96.0f, 636.0f, 84.0f, 0.952941f, 0.945098f, 0.886275f, 12.0f, "Hello PS5", false},
}};

}
)cpp";

void writeText(const QString& path, const QByteArray& text = "x") {
    QDir().mkpath(QFileInfo(path).absolutePath());
    QFile file(path);
    QVERIFY(file.open(QIODevice::WriteOnly));
    file.write(text);
}

QByteArray readBytes(const QString& path) {
    QFile file(path);
    return file.open(QIODevice::ReadOnly) ? file.readAll() : QByteArray();
}

SceneItem rectangle(const QString& id = "r", const QString& name = "Box") {
    SceneItem item;
    item.id = id;
    item.type = "rectangle";
    item.name = name;
    item.x = 10;
    item.y = 20;
    item.width = 30;
    item.height = 40;
    return item;
}

SceneItem label(const QString& id = "t", const QString& name = "Title", const QString& text = "Hi") {
    SceneItem item;
    item.id = id;
    item.type = "text";
    item.name = name;
    item.x = 5;
    item.y = 6;
    item.scale = 2;
    item.text = text;
    return item;
}

QJsonObject docObject() {
    return QJsonDocument::fromJson(DocExample).object();
}

using Mutation = std::function<void(QJsonObject&)>;

// Applies `change` to one item of the doc's example: 0 is the rectangle, 1 is the text.
Mutation onItem(int index, const std::function<void(QJsonObject&)>& change) {
    return [=](QJsonObject& root) {
        auto items = root["items"].toArray();
        auto item = items[index].toObject();
        change(item);
        items[index] = item;
        root["items"] = items;
    };
}

Mutation setField(int index, const QString& key, const QJsonValue& value) {
    return onItem(index, [=](QJsonObject& item) { item[key] = value; });
}

Mutation removeField(int index, const QString& key) {
    return onItem(index, [=](QJsonObject& item) { item.remove(key); });
}

SceneLoadResult loadMutated(const Mutation& mutate) {
    QTemporaryDir directory;
    auto root = docObject();
    mutate(root);
    const auto path = directory.path() + "/scene.json";
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly)) return {std::nullopt, "test could not write scene"};
    file.write(QJsonDocument(root).toJson());
    file.close();
    return loadScene(path);
}

Scene sceneOfSize(int count) {
    Scene scene;
    for (int index = 0; index < count; ++index) scene.items.append(rectangle(QString("item-%1").arg(index)));
    return scene;
}

QStringList backupFolders(const QString& root) {
    return QDir(root + "/.studio-backup").entryList(QDir::Dirs | QDir::NoDotAndDotDot, QDir::Name);
}

QStringList allFiles(const QString& root) {
    QStringList files;
    QDirIterator iterator(root, QDir::Files | QDir::Hidden | QDir::NoDotAndDotDot, QDirIterator::Subdirectories);
    while (iterator.hasNext()) files << QDir(root).relativeFilePath(iterator.next());
    files.sort();
    return files;
}

