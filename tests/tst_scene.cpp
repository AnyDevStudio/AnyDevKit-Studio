void writeText(const QString& path, const QByteArray& text = "x") {
    QDir().mkpath(QFileInfo(path).absolutePath());
    QFile file(path);
    QVERIFY(file.open(QIODevice::WriteOnly));
    file.write(text);
}

QByteArray readBytes(const QString& path) {
    QFile file(path);
    return file.open(QIODevice::ReadOnly) ? file.readAll() : QByteArray();
}

SceneImageData pixels(const QString& source, int width, int height) {
    QByteArray data;
    data.resize(width * height * 4);
    for (qsizetype index = 0; index < data.size(); ++index) data[index] = char(index);
    return {source, width, height, data};
}

