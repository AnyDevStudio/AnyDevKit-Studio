QJsonObject docObject() {
    return QJsonDocument::fromJson(DocExample).object();
}

using Mutation = std::function<void(QJsonObject&)>;

// Applies `change` to one item of the doc's example: 0 is the rectangle, 1 is the text.
Mutation onItem(int index, const std::function<void(QJsonObject&)>& change) {
    return [=](QJsonObject& root) {
        auto items = root["items"].toArray();
        auto item = items[index].toObject();
        change(item);
        items[index] = item;
        root["items"] = items;
    };
}

Mutation setField(int index, const QString& key, const QJsonValue& value) {
    return onItem(index, [=](QJsonObject& item) { item[key] = value; });
}

Mutation removeField(int index, const QString& key) {
    return onItem(index, [=](QJsonObject& item) { item.remove(key); });
}

SceneLoadResult loadMutated(const Mutation& mutate) {
    QTemporaryDir directory;
    auto root = docObject();
    mutate(root);
    const auto path = directory.path() + "/scene.json";
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly)) return {std::nullopt, "test could not write scene"};
    file.write(QJsonDocument(root).toJson());
    file.close();
    return loadScene(path);
}

Scene sceneOfSize(int count) {
    Scene scene;
    for (int index = 0; index < count; ++index) scene.items.append(rectangle(QString("item-%1").arg(index)));
    return scene;
}

QStringList backupFolders(const QString& root) {
    return QDir(root + "/.studio-backup").entryList(QDir::Dirs | QDir::NoDotAndDotDot, QDir::Name);
}

QStringList allFiles(const QString& root) {
    QStringList files;
    QDirIterator iterator(root, QDir::Files | QDir::Hidden | QDir::NoDotAndDotDot, QDirIterator::Subdirectories);
    while (iterator.hasNext()) files << QDir(root).relativeFilePath(iterator.next());
    files.sort();
    return files;
}

